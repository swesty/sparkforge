const GEMV: &str = r#"
namespace @NS@ {
constexpr int N = @N@, K = @K@, WARPS = @WARPS@, RPW = @RPW@;
static_assert(K % 8 == 0, "K must allow 16B vector loads");
}
// Decode GEMV y[N] = W[N,K] . x[K], bf16 weights streamed with evict-first loads.
extern "C" __global__ void __launch_bounds__(@NS@::WARPS * 32)
@ENTRY@(const bf16* __restrict__ W, const bf16* __restrict__ x, bf16* __restrict__ y) {
  using namespace @NS@;
  extern __shared__ uint4 xs[];  // K/8 vectors
  for (int c = threadIdx.x; c < K / 8; c += WARPS * 32) xs[c] = reinterpret_cast<const uint4*>(x)[c];
  __syncthreads();
  const int warp = threadIdx.x >> 5, lane = threadIdx.x & 31;
  const int row0 = (blockIdx.x * WARPS + warp) * RPW;
  if (row0 >= N) return;
  float acc[RPW];
#pragma unroll
  for (int r = 0; r < RPW; ++r) acc[r] = 0.f;
#pragma unroll 4
  for (int c = lane; c < K / 8; c += 32) {
    float xf[8]; unpack8(xs[c], xf);
#pragma unroll
    for (int r = 0; r < RPW; ++r) {
      if (row0 + r < N) {
        float wf[8]; unpack8(__ldcs(reinterpret_cast<const uint4*>(W + (size_t)(row0 + r) * K) + c), wf);
#pragma unroll
        for (int j = 0; j < 8; ++j) acc[r] += wf[j] * xf[j];
      }
    }
  }
#pragma unroll
  for (int r = 0; r < RPW; ++r) {
    const float s = warp_sum(acc[r]);
    if (lane == 0 && row0 + r < N) y[row0 + r] = __float2bfloat16(s);
  }
}
"#;

