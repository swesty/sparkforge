//! Emits CUDA C++ with every model dimension baked in as `constexpr`, so NVRTC can fully
//! unroll loops, drop bounds checks, and pick register allocations per shape.
use crate::config::{ModelSpec, RopeScaling};
use crate::plan::Plan;
use serde::Serialize;
use sha2::{Digest, Sha256};

#[derive(Debug, Clone, Serialize)]
pub struct KernelEntry {
    pub entry: String,
    pub file: String,
    pub grid: [u32; 3],
    pub block: u32,
    pub dyn_smem: u32,
    /// "generated" = real kernel, "planned" = tile config chosen, kernel body still TODO.
    pub status: &'static str,
    pub args: Vec<&'static str>,
}

#[derive(Debug, Clone, Serialize)]
pub struct Generated {
    pub arch: String,
    pub cache_key: String,
    pub files: Vec<(String, String)>,
    pub kernels: Vec<KernelEntry>,
}

const PRELUDE: &str = r#"// Generated by sparkforge for @MODEL@ on @ARCH@. Do not edit.
#include <cuda_bf16.h>
typedef __nv_bfloat16 bf16;
#define NEG_INF (__int_as_float(0xff800000))
__device__ __forceinline__ float warp_sum(float v) {
#pragma unroll
  for (int o = 16; o > 0; o >>= 1) v += __shfl_xor_sync(0xffffffffu, v, o);
  return v;
}
__device__ __forceinline__ void unpack8(const uint4& p, float* f) {
  const bf16* e = reinterpret_cast<const bf16*>(&p);
#pragma unroll
  for (int j = 0; j < 8; ++j) f[j] = __bfloat162float(e[j]);
}
"#;

const RMSNORM: &str = r#"
namespace rmsnorm_ns {
constexpr int HIDDEN = @HIDDEN@, THREADS = @THREADS@, ITERS = @ITERS@;
static_assert(HIDDEN == THREADS * ITERS * 8, "rmsnorm shape mismatch");
}
extern "C" __global__ void __launch_bounds__(rmsnorm_ns::THREADS)
rmsnorm(const bf16* __restrict__ x, const bf16* __restrict__ w, bf16* __restrict__ y, float eps) {
  using namespace rmsnorm_ns;
  const uint4* xr = reinterpret_cast<const uint4*>(x + (size_t)blockIdx.x * HIDDEN);
  float v[ITERS][8]; float ss = 0.f;
#pragma unroll
  for (int i = 0; i < ITERS; ++i) {
    unpack8(xr[i * THREADS + threadIdx.x], v[i]);
#pragma unroll
    for (int j = 0; j < 8; ++j) ss += v[i][j] * v[i][j];
  }
  __shared__ float red[32];
  ss = warp_sum(ss);
  if ((threadIdx.x & 31) == 0) red[threadIdx.x >> 5] = ss;
  __syncthreads();
  if (threadIdx.x < 32) {
    float t = threadIdx.x < THREADS / 32 ? red[threadIdx.x] : 0.f;
    t = warp_sum(t);
    if (threadIdx.x == 0) red[0] = t;
  }
  __syncthreads();
  const float inv = rsqrtf(red[0] / HIDDEN + eps);
  const uint4* wr = reinterpret_cast<const uint4*>(w);
  uint4* yr = reinterpret_cast<uint4*>(y + (size_t)blockIdx.x * HIDDEN);
#pragma unroll
  for (int i = 0; i < ITERS; ++i) {
    float wf[8]; unpack8(wr[i * THREADS + threadIdx.x], wf);
    uint4 out; bf16* o = reinterpret_cast<bf16*>(&out);
#pragma unroll
    for (int j = 0; j < 8; ++j) o[j] = __float2bfloat16(v[i][j] * inv * wf[j]);
    yr[i * THREADS + threadIdx.x] = out;
  }
}
"#;

const ROPE_KV: &str = r#"
namespace rope_ns {
constexpr int HD = @HD@, HEADS = @HEADS@, KVH = @KVH@;
// inv_freq[i] = 1 / theta^(2i/HD), computed on the host in f32 exactly as HF transformers does.
__constant__ float INV_FREQ[HD / 2] = {@INV_FREQ@};
}
// Decode step, one token: rotates q and k in the fused qkv buffer (NeoX half-split layout)
// and appends k/v into the cache at `pos`. Grid = HEADS + 2*KVH, block = HD/2.
extern "C" __global__ void __launch_bounds__(rope_ns::HD / 2)
rope_kv_append(bf16* __restrict__ qkv, bf16* __restrict__ k_cache, bf16* __restrict__ v_cache, int pos) {
  using namespace rope_ns;
  const int h = blockIdx.x, i = threadIdx.x;
  bf16* base = qkv + (size_t)h * HD;
  if (h < HEADS + KVH) {
    // The angle is formed in f32 (as HF does), but sin/cos must be precise: under --use_fast_math
    // sincosf becomes __sincosf, whose error grows with |angle| (pos * inv_freq reaches ~1e5 rad).
    // Double sincos is not affected by fast-math, and 64 threads x 1 call is negligible.
    double sd, cd; sincos((double)((float)pos * INV_FREQ[i]), &sd, &cd);
    const float s = (float)sd, c = (float)cd;
    const float x1 = __bfloat162float(base[i]), x2 = __bfloat162float(base[i + HD / 2]);
    const bf16 r1 = __float2bfloat16(x1 * c - x2 * s), r2 = __float2bfloat16(x2 * c + x1 * s);
    base[i] = r1; base[i + HD / 2] = r2;
    if (h >= HEADS) {
      bf16* kc = k_cache + ((size_t)pos * KVH + (h - HEADS)) * HD;
      kc[i] = r1; kc[i + HD / 2] = r2;
    }
  } else {
    bf16* vc = v_cache + ((size_t)pos * KVH + (h - HEADS - KVH)) * HD;
    vc[i] = base[i]; vc[i + HD / 2] = base[i + HD / 2];
  }
}
"#;

const ATTN: &str = r#"
namespace attn_ns {
constexpr int HD = @HD@, KVH = @KVH@, GROUP = @GROUP@, WARPS = @WARPS@, SPLITS = @SPLITS@;
constexpr int DPL = HD / 32;  // head dims owned by each lane
static_assert(HD % 32 == 0, "head_dim must be a multiple of 32");
}
// Flash-decoding, GQA-aware: one CTA per (kv_head, split) serves all GROUP query heads that
// share that kv head, so each K/V row is read from DRAM exactly once per split.
extern "C" __global__ void __launch_bounds__(attn_ns::WARPS * 32, 2)
attn_decode_split(const bf16* __restrict__ q, const bf16* __restrict__ k_cache,
                  const bf16* __restrict__ v_cache, float* __restrict__ part_ml,
                  float* __restrict__ part_acc, int seq_len, float scale) {
  using namespace attn_ns;
  extern __shared__ float sm[];  // [WARPS][GROUP][HD + 2]
  const int kvh = blockIdx.x, split = blockIdx.y;
  const int warp = threadIdx.x >> 5, lane = threadIdx.x & 31;
  const int chunk = (seq_len + SPLITS - 1) / SPLITS;
  const int t0 = split * chunk, t1 = min(seq_len, t0 + chunk);
  float qv[GROUP][DPL], acc[GROUP][DPL], m[GROUP], l[GROUP];
#pragma unroll
  for (int g = 0; g < GROUP; ++g) {
    m[g] = NEG_INF; l[g] = 0.f;
#pragma unroll
    for (int d = 0; d < DPL; ++d) {
      qv[g][d] = __bfloat162float(q[(size_t)(kvh * GROUP + g) * HD + lane * DPL + d]) * scale;
      acc[g][d] = 0.f;
    }
  }
  for (int t = t0 + warp; t < t1; t += WARPS) {
    const size_t off = ((size_t)t * KVH + kvh) * HD + lane * DPL;
    float kf[DPL], vf[DPL];
#pragma unroll
    for (int d = 0; d < DPL; ++d) { kf[d] = __bfloat162float(k_cache[off + d]); vf[d] = __bfloat162float(v_cache[off + d]); }
#pragma unroll
    for (int g = 0; g < GROUP; ++g) {
      float s = 0.f;
#pragma unroll
      for (int d = 0; d < DPL; ++d) s += qv[g][d] * kf[d];
      s = warp_sum(s);
      const float mn = fmaxf(m[g], s), c = __expf(m[g] - mn), p = __expf(s - mn);
      l[g] = l[g] * c + p;
#pragma unroll
      for (int d = 0; d < DPL; ++d) acc[g][d] = acc[g][d] * c + p * vf[d];
      m[g] = mn;
    }
  }
#pragma unroll
  for (int g = 0; g < GROUP; ++g) {
    float* row = sm + (warp * GROUP + g) * (HD + 2);
#pragma unroll
    for (int d = 0; d < DPL; ++d) row[lane * DPL + d] = acc[g][d];
    if (lane == 0) { row[HD] = m[g]; row[HD + 1] = l[g]; }
  }
  __syncthreads();
  for (int idx = threadIdx.x; idx < GROUP * HD; idx += WARPS * 32) {
    const int g = idx / HD, d = idx % HD;
    float M = NEG_INF;
#pragma unroll
    for (int w = 0; w < WARPS; ++w) M = fmaxf(M, sm[(w * GROUP + g) * (HD + 2) + HD]);
    float L = 0.f, O = 0.f;
    if (M != NEG_INF) {
#pragma unroll
      for (int w = 0; w < WARPS; ++w) {
        const float* row = sm + (w * GROUP + g) * (HD + 2);
        const float e = __expf(row[HD] - M);
        L += row[HD + 1] * e; O += row[d] * e;
      }
    }
    const size_t pi = ((size_t)kvh * SPLITS + split) * GROUP + g;
    part_acc[pi * HD + d] = O;
    if (d == 0) { part_ml[pi * 2] = M; part_ml[pi * 2 + 1] = L; }
  }
}
// Merge splits. Grid = HEADS, block = HD.
extern "C" __global__ void __launch_bounds__(attn_ns::HD)
attn_decode_combine(const float* __restrict__ part_ml, const float* __restrict__ part_acc, bf16* __restrict__ out) {
  using namespace attn_ns;
  const int h = blockIdx.x, kvh = h / GROUP, g = h % GROUP, d = threadIdx.x;
  float M = NEG_INF;
#pragma unroll
  for (int s = 0; s < SPLITS; ++s) M = fmaxf(M, part_ml[(((size_t)kvh * SPLITS + s) * GROUP + g) * 2]);
  float L = 0.f, O = 0.f;
#pragma unroll
  for (int s = 0; s < SPLITS; ++s) {
    const size_t pi = ((size_t)kvh * SPLITS + s) * GROUP + g;
    const float ms = part_ml[pi * 2];
    if (ms == NEG_INF) continue;
    const float e = __expf(ms - M);
    L += part_ml[pi * 2 + 1] * e; O += part_acc[pi * HD + d] * e;
  }
  out[(size_t)h * HD + d] = __float2bfloat16(O / L);
}
"#;

const SILU_MUL: &str = r#"
namespace silu_ns { constexpr int INTER = @INTER@; static_assert(INTER % 8 == 0, ""); }
// gate_up = [gate(INTER) | up(INTER)] -> out = silu(gate) * up. One thread per 8 elements.
extern "C" __global__ void __launch_bounds__(256)
silu_mul(const bf16* __restrict__ gate_up, bf16* __restrict__ out) {
  using namespace silu_ns;
  const int v = blockIdx.x * 256 + threadIdx.x;
  if (v >= INTER / 8) return;
  const uint4* gp = reinterpret_cast<const uint4*>(gate_up);
  float g[8], u[8]; unpack8(gp[v], g); unpack8(gp[INTER / 8 + v], u);
  uint4 r; bf16* o = reinterpret_cast<bf16*>(&r);
#pragma unroll
  for (int j = 0; j < 8; ++j) o[j] = __float2bfloat16(g[j] / (1.f + __expf(-g[j])) * u[j]);
  reinterpret_cast<uint4*>(out)[v] = r;
}
"#;

const GEMV: &str = r#"
namespace @NS@ {
constexpr int N = @N@, K = @K@, WARPS = @WARPS@, RPW = @RPW@;
static_assert(K % 8 == 0, "K must allow 16B vector loads");
}
// Decode GEMV y[N] = W[N,K] . x[K], bf16 weights streamed with evict-first loads.
extern "C" __global__ void __launch_bounds__(@NS@::WARPS * 32)
@ENTRY@(const bf16* __restrict__ W, const bf16* __restrict__ x, bf16* __restrict__ y) {
  using namespace @NS@;
  extern __shared__ uint4 xs[];  // K/8 vectors
  for (int c = threadIdx.x; c < K / 8; c += WARPS * 32) xs[c] = reinterpret_cast<const uint4*>(x)[c];
  __syncthreads();
  const int warp = threadIdx.x >> 5, lane = threadIdx.x & 31;
  const int row0 = (blockIdx.x * WARPS + warp) * RPW;
  if (row0 >= N) return;
  float acc[RPW];
#pragma unroll
  for (int r = 0; r < RPW; ++r) acc[r] = 0.f;
#pragma unroll 4
  for (int c = lane; c < K / 8; c += 32) {
    float xf[8]; unpack8(xs[c], xf);
#pragma unroll
    for (int r = 0; r < RPW; ++r) {
      if (row0 + r < N) {
        float wf[8]; unpack8(__ldcs(reinterpret_cast<const uint4*>(W + (size_t)(row0 + r) * K) + c), wf);
#pragma unroll
        for (int j = 0; j < 8; ++j) acc[r] += wf[j] * xf[j];
      }
    }
  }
#pragma unroll
  for (int r = 0; r < RPW; ++r) {
    const float s = warp_sum(acc[r]);
    if (lane == 0 && row0 + r < N) y[row0 + r] = __float2bfloat16(s);
  }
}
"#;

/// RoPE inverse frequencies exactly as HF transformers computes them in f32:
/// `1.0 / (base ** (arange(0, dim, 2).float() / dim))`, then `rope_scaling` if present.
pub fn rope_inv_freq(m: &ModelSpec) -> Vec<f32> {
    let (theta, hd) = (m.rope_theta as f32, m.head_dim);
    (0..hd / 2)
        .map(|i| {
            let f = 1.0f32 / theta.powf((2 * i) as f32 / hd as f32);
            match m.rope_scaling {
                None => f,
                // transformers `_compute_llama3_parameters`
                Some(RopeScaling::Llama3 { factor, low_freq_factor, high_freq_factor, original_max_pos }) => {
                    let (factor, lo, hi, old) = (factor as f32, low_freq_factor as f32, high_freq_factor as f32, original_max_pos as f32);
                    let wavelen = 2.0 * std::f32::consts::PI / f;
                    if wavelen < old / hi {
                        f
                    } else if wavelen > old / lo {
                        f / factor
                    } else {
                        let smooth = (old / wavelen - lo) / (hi - lo);
                        (1.0 - smooth) * f / factor + smooth * f
                    }
                }
            }
        })
        .collect()
}

fn fill(t: &str, kv: &[(&str, String)]) -> String {
    let mut s = t.to_string();
    for (k, v) in kv { s = s.replace(&format!("@{k}@"), v); }
    s
}

pub fn generate(p: &Plan) -> Generated {
    let m = &p.model;
    let mut kernels = vec![];
    let mut src = fill(PRELUDE, &[("MODEL", m.arch.clone()), ("ARCH", p.target.arch.into())]);

    src += &fill(RMSNORM, &[("HIDDEN", m.hidden.to_string()), ("THREADS", p.norm.threads.to_string()), ("ITERS", p.norm.iters.to_string())]);
    kernels.push(KernelEntry { entry: "rmsnorm".into(), file: "model.cu".into(), grid: [1, 1, 1], block: p.norm.threads, dyn_smem: 0, status: "generated", args: vec!["x", "w", "y", "eps"] });

    src += &fill(ROPE_KV, &[("HD", m.head_dim.to_string()), ("HEADS", m.heads.to_string()), ("KVH", m.kv_heads.to_string()), ("INV_FREQ", rope_inv_freq(m).iter().map(|v| format!("{v:e}f")).collect::<Vec<_>>().join(", "))]);
    kernels.push(KernelEntry { entry: "rope_kv_append".into(), file: "model.cu".into(), grid: [m.heads + 2 * m.kv_heads, 1, 1], block: m.head_dim / 2, dyn_smem: 0, status: "generated", args: vec!["qkv", "k_cache", "v_cache", "pos"] });

    let a = &p.attn;
    src += &fill(ATTN, &[("HD", a.head_dim.to_string()), ("KVH", a.kv_heads.to_string()), ("GROUP", a.group.to_string()), ("WARPS", a.warps.to_string()), ("SPLITS", a.splits.to_string())]);
    kernels.push(KernelEntry { entry: "attn_decode_split".into(), file: "model.cu".into(), grid: [a.grid[0], a.grid[1], 1], block: a.warps * 32, dyn_smem: a.smem_bytes, status: "generated", args: vec!["q", "k_cache", "v_cache", "part_ml", "part_acc", "seq_len", "scale"] });
    kernels.push(KernelEntry { entry: "attn_decode_combine".into(), file: "model.cu".into(), grid: [m.heads, 1, 1], block: m.head_dim, dyn_smem: 0, status: "generated", args: vec!["part_ml", "part_acc", "out"] });

    let inter = m.moe.as_ref().map_or(m.intermediate, |e| e.expert_intermediate);
    src += &fill(SILU_MUL, &[("INTER", inter.to_string())]);
    kernels.push(KernelEntry { entry: "silu_mul".into(), file: "model.cu".into(), grid: [(inter / 8).div_ceil(256), 1, 1], block: 256, dyn_smem: 0, status: "generated", args: vec!["gate_up", "out"] });

    for g in &p.gemv {
        let entry = format!("gemv_{}", g.linear);
        src += &fill(GEMV, &[("NS", format!("{entry}_ns")), ("ENTRY", entry.clone()), ("N", g.n.to_string()), ("K", g.k.to_string()), ("WARPS", g.warps_per_block.to_string()), ("RPW", g.rows_per_warp.to_string())]);
        let fmt_ok = g.linear == "lm_head" || g.linear == "router" || matches!(m.weights, crate::config::WeightFormat::Bf16);
        kernels.push(KernelEntry { entry, file: "model.cu".into(), grid: [g.grid, 1, 1], block: g.warps_per_block * 32, dyn_smem: g.smem_bytes, status: if fmt_ok { "generated" } else { "planned" }, args: vec!["W", "x", "y"] });
    }

    let mut tiles = String::from("// Prefill GEMM tile configs chosen by the planner (mma.sync m16n8k16 bf16, cp.async/TMA pipeline).\n#pragma once\n");
    for t in &p.gemm {
        tiles += &format!("struct Tile_{} {{ static constexpr int M = {}, N = {}, K = {}, BM = {}, BN = {}, BK = {}, STAGES = {}, WARPS = {}, SMEM = {}; }};\n", t.linear, t.m, t.n, t.k, t.bm, t.bn, t.bk, t.stages, t.warps, t.smem_bytes);
        kernels.push(KernelEntry { entry: format!("gemm_{}", t.linear), file: "gemm_tiles.cuh".into(), grid: [t.n.div_ceil(t.bn), t.m.div_ceil(t.bm), 1], block: t.warps * 32, dyn_smem: t.smem_bytes, status: "planned", args: vec!["A", "W", "C"] });
    }

    let mut h = Sha256::new();
    h.update(p.target.arch.as_bytes()); h.update(src.as_bytes()); h.update(tiles.as_bytes());
    let key = h.finalize().iter().take(8).map(|b| format!("{b:02x}")).collect::<String>();
    Generated { arch: p.target.arch.into(), cache_key: key, files: vec![("model.cu".into(), src), ("gemm_tiles.cuh".into(), tiles)], kernels }
}
