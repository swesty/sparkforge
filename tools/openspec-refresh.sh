#!/usr/bin/env bash
# Regenerate this repo's OpenSpec skills with the pinned OpenSpec version. Use this instead of a
# bare `openspec update`. Never run `openspec update --force` here: it also deletes the global
# ~/.codex/prompts/opsx-* files that other repos use.
#
# Why a script:
# - A contributor whose PATH still resolves an older OpenSpec (1.x generated the removed
#   .claude/commands/opsx layout) must be stopped before anything is written.
# - Spec merging and archiving stay with the deterministic CLI (`openspec archive <change>`).
#   The agent-driven openspec-sync-specs and openspec-archive-change skills that `openspec update`
#   installs are removed: codex-review found their 2.1.1 instructions can write outside the specs
#   root through a symlink, leave a multi-capability sync half-applied, race the archive move, and
#   overwrite a re-synced ADDED requirement (upstream Fission-AI/OpenSpec#2289).
#
# Safety properties (tools/test-openspec-refresh.sh checks each one with a stub openspec):
# - The repository is the one that contains this script, never the caller's working directory.
# - The excluded skills are removed even when `openspec update` fails, and the failure status is
#   kept.
# - Only the generated SKILL.md is deleted from an excluded skill directory. Anything else in it is
#   reported and left in place.
# - Each .claude/skills/openspec-* link must resolve to its own .agents/skills directory.
set -euo pipefail

PINNED="2.1.1"
EXCLUDED=(openspec-sync-specs openspec-archive-change)
EXPECTED=(openspec-apply-change openspec-explore openspec-propose openspec-update-change)

# Resolve the repository from this script's own location, so running it by absolute path from
# another checkout can never update or delete files in that checkout.
SCRIPT_DIR="$(cd -P "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)"
ROOT="$(git -C "$SCRIPT_DIR" rev-parse --show-toplevel)"
if [ ! -f "$ROOT/openspec/config.yaml" ] || [ ! "$ROOT/tools/openspec-refresh.sh" -ef "${BASH_SOURCE[0]}" ]; then
  echo "openspec-refresh: $ROOT does not look like the sparkforge repo; nothing was changed." >&2
  exit 1
fi
cd "$ROOT"

if ! command -v openspec >/dev/null 2>&1; then
  echo "openspec-refresh: openspec is not on PATH; install it with: npm install -g @fission-ai/openspec@$PINNED" >&2
  exit 1
fi
FOUND="$(openspec --version 2>/dev/null | tr -d '[:space:]')"
if [ "$FOUND" != "$PINNED" ]; then
  echo "openspec-refresh: found OpenSpec '$FOUND' at $(command -v openspec), this repo pins $PINNED." >&2
  echo "openspec-refresh: nothing was changed. Install the pinned version: npm install -g @fission-ai/openspec@$PINNED" >&2
  exit 1
fi

# Disable one excluded skill. Deletes only what OpenSpec generates (SKILL.md, and the Claude link)
# and reports anything else instead of deleting it. Returns 0 when the skill is no longer
# discoverable, 1 otherwise.
disable_skill() {
  local skill="$1" dir=".agents/skills/$1" link=".claude/skills/$1" ok=0 left
  if [ -L "$dir" ]; then
    # A link here could point anywhere; remove the link, never what it points to.
    rm -f -- "$dir"
  elif [ -d "$dir" ]; then
    if [ -f "$dir/SKILL.md" ] || [ -L "$dir/SKILL.md" ]; then rm -f -- "$dir/SKILL.md"; fi
    rmdir -- "$dir" 2>/dev/null || {
      left="$(cd "$dir" && find . -mindepth 1 -print | sed 's|^\./||' | sort | tr '\n' ' ')"
      echo "openspec-refresh: kept unexpected files in $dir (not generated by OpenSpec): $left" >&2
    }
  fi
  if [ -L "$link" ]; then
    rm -f -- "$link"
  elif [ -d "$link" ]; then
    if [ -f "$link/SKILL.md" ] || [ -L "$link/SKILL.md" ]; then rm -f -- "$link/SKILL.md"; fi
    rmdir -- "$link" 2>/dev/null || echo "openspec-refresh: kept unexpected files in $link" >&2
  fi
  # The skill must not be discoverable from either location.
  if [ -e "$dir/SKILL.md" ] || [ -L "$dir/SKILL.md" ] || [ -e "$link/SKILL.md" ] || [ -L "$link/SKILL.md" ]; then
    echo "openspec-refresh: excluded skill $skill is still discoverable" >&2
    ok=1
  fi
  return "$ok"
}

disable_excluded() {
  local skill fail=0
  for skill in "${EXCLUDED[@]}"; do disable_skill "$skill" || fail=1; done
  return "$fail"
}

# Spec merging and archiving belong to the CLI here, not to agent-followed instructions. Remove the
# excluded skills on every exit from here on, including a failed or interrupted update, and keep
# the original failure status.
DISABLED=0
on_exit() {
  local rc=$?
  trap - EXIT
  if [ "$DISABLED" -ne 1 ]; then disable_excluded || { [ "$rc" -ne 0 ] || rc=1; }; fi
  exit "$rc"
}
trap on_exit EXIT
trap 'exit 130' INT
trap 'exit 143' TERM

# Non-interactive; openspec/config.yaml records skillsScope: project, so skills stay in the repo.
openspec update "$ROOT"

disable_excluded
DISABLED=1

# Check the layout this repo expects.
fail=0
for skill in "${EXPECTED[@]}"; do
  canon=".agents/skills/$skill"
  link=".claude/skills/$skill"
  if [ ! -f "$canon/SKILL.md" ]; then
    echo "openspec-refresh: missing $canon/SKILL.md" >&2; fail=1; continue
  fi
  if [ ! -L "$link" ]; then
    echo "openspec-refresh: $link is not a link into .agents/skills" >&2; fail=1; continue
  fi
  # The link must resolve to this skill's own directory, not to a missing path or a stale copy.
  want="$(cd -P "$canon" && pwd -P)"
  got="$(cd -P "$link" 2>/dev/null && pwd -P)" || got=""
  if [ -z "$got" ]; then
    echo "openspec-refresh: $link is dangling (-> $(readlink "$link"))" >&2; fail=1; continue
  fi
  if [ "$got" != "$want" ]; then
    echo "openspec-refresh: $link resolves to $got, expected $want" >&2; fail=1; continue
  fi
  [ -f "$link/SKILL.md" ] || { echo "openspec-refresh: $link does not expose SKILL.md" >&2; fail=1; }
done
[ ! -e ".claude/commands/opsx" ] || { echo "openspec-refresh: legacy .claude/commands/opsx is present" >&2; fail=1; }
exit "$fail"
